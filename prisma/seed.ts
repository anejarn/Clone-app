/**
 * Resets demo data. Safe to re-run: it clears catalogue and activity tables first.
 * Users who signed up (no demo.sigma.test email) are kept, but their bookings, reviews and wishlist items
 * on demo listings are removed with them. Amounts are centimes of dirham (MAD).
 * Everything belongs to the Sigma organization (created by the organizations_and_roles migration, upserted here):
 * its team, its owners (propriétaires) and their listings, which take the organization's default commission
 * (0 for sub-lets).
 * Bookings: direct stays of demo guest accounts, platform bookings (Airbnb, Booking.com, Agoda, Trip.com) of guests
 * without an account, and a few owner blocks; none overlap (prisma/fixtures.ts). Seasons and events (Prix) for a
 * selection of homes; booking amounts are priced with them by the pricing engine.
 * Field tasks (Opérations): the default French check-lists, then the tasks of every stay not over yet, generated by
 * the app's own code (lib/operations/sync.ts); those of the coming week are shared between the two agents, every
 * third one left unassigned. Two breakdown reports (Pannes), one of them urgent. Conciergerie: fictitious partners
 * and services, two requests on the demo stay in progress.
 */
import "dotenv/config";
import { PrismaPg } from "@prisma/adapter-pg";
import { hashPassword, symmetricEncrypt } from "better-auth/crypto";
import { PrismaClient } from "../lib/generated/prisma/client";
import { hashGuideToken } from "../lib/guide/token";
import { DEFAULT_CHECKLISTS } from "../lib/operations/checklist";
import { encryptSecret } from "../lib/secrets/access-codes";
import { encryptIdentity } from "../lib/secrets/identity";
import { computeStayTax, taxGuests } from "../lib/tax/engine";
import { backfillTasks } from "../lib/operations/sync";
import { postExpense, syncBookingFinance } from "../lib/finance/post";
import { priceStay, type PricingRule } from "../lib/pricing";
import { lineTotals } from "../lib/concierge/pricing";
import { localInstant } from "../lib/operations/schedule";
import {
  AMENITIES,
  buildBookings,
  buildChannelBookings,
  buildFixtures,
  buildLicenses,
  buildPriceRules,
  DEMO_BACKUP_CODES,
  DEMO_CONCIERGE,
  DEMO_GUIDE_TOKENS,
  DEMO_RECOMMENDATIONS,
  demoAccessCodes,
  demoGuideTexts,
  demoWifi,
  DEMO_LOGINS,
  DEMO_PARTNERS,
  DEMO_SERVICES,
  DEMO_PASSWORD,
  DEMO_TOTP_SECRET,
  DEMO_TAX_RATE,
  DEMO_TRAVELERS,
  SIGMA_ORG,
} from "./fixtures";

const DEMO_DOMAINS = ["@demo.sigma.test", "@demo.nidou.fr"];
const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) });

async function main() {
  const { places, staff, owners, guests, listings, reviews } = buildFixtures();
  const now = new Date();
  const today = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate()));
  const bookings = buildBookings(listings, guests, today);
  const { platform, ownerBlocks } = buildChannelBookings(listings, today);
  const licenses = new Map(buildLicenses(listings, today).map((l) => [l.listingId, l]));

  await prisma.$transaction([
    // Finances (Lot 6): the journal is append-only and validated expenses are frozen (database triggers); this demo
    // reset is the one place allowed to clear them, for this transaction only (sigma.ledger_reset). Never in production.
    prisma.$queryRaw`SELECT set_config('sigma.ledger_reset', 'on', true)`,
    prisma.financialEntry.deleteMany(),
    // Lot 6b: statements and transfers are immutable too (same setting); owner documents hold their homes.
    prisma.ownerPayout.deleteMany(),
    prisma.ownerStatement.deleteMany(),
    prisma.ownerDocument.deleteMany(),
    prisma.expense.deleteMany(),
    prisma.financeMonthClosing.deleteMany(),
    // Conciergerie (Lot 4b): requests hold their booking, service and partner (restricted), so they go first.
    prisma.serviceRequest.deleteMany(),
    prisma.service.deleteMany(),
    prisma.partner.deleteMany(),
    // Tasks and tickets go with their bookings and listings (cascade); deleted first all the same, manual ones included.
    prisma.ticket.deleteMany(),
    prisma.task.deleteMany(),
    prisma.priceRule.deleteMany(),
    // Lot 5: travellers and tax snapshots go with their bookings; rates and purge traces are the organizations'.
    prisma.touristTaxRate.deleteMany(),
    prisma.identityPurge.deleteMany(),
    // Guides, codes, photos and links go with their listings and bookings; the organizations' common recommendations don't.
    prisma.guideRecommendation.deleteMany(),
    prisma.wishlistItem.deleteMany(),
    prisma.booking.deleteMany(),
    prisma.review.deleteMany(),
    prisma.listingAmenity.deleteMany(),
    prisma.photo.deleteMany(),
    prisma.listing.deleteMany(),
    prisma.amenity.deleteMany(),
    prisma.place.deleteMany(),
    // Demo users only; @demo.nidou.fr is the fixture domain used before the rename to Sigma.
    prisma.user.deleteMany({ where: { OR: DEMO_DOMAINS.map((d) => ({ email: { endsWith: d } })) } }),
    // Accounts the test suites created (@test.sigma.test) and left behind: the suites clean up after themselves, this
    // catches what an interrupted run left (it slowed Utilisateurs down). Never a real address: the domain is reserved.
    prisma.user.deleteMany({ where: { email: { endsWith: "@test.sigma.test" } } }),
  ], { timeout: 60_000 });

  const org = await prisma.organization.upsert({
    where: { slug: SIGMA_ORG.slug },
    create: SIGMA_ORG,
    update: { name: SIGMA_ORG.name },
    select: { id: true, defaultCommissionBps: true },
  });
  const organizationId = org.id;

  await prisma.user.createMany({
    data: [
      ...[...staff, ...owners].map((u) => ({ ...u, emailVerified: true, organizationId })),
      ...guests.map((u) => ({ ...u, emailVerified: true })),
    ],
  });
  await seedDemoLogins();
  await prisma.place.createMany({ data: places });
  const placeIds = new Map((await prisma.place.findMany({ select: { id: true, slug: true } })).map((p) => [p.slug, p.id]));
  await prisma.amenity.createMany({ data: AMENITIES.map(([id, label, icon, group]) => ({ id, label, icon, group })) });

  // Rating aggregates are computed here once; lib/server/reviews.ts keeps them current afterwards.
  const stats = new Map<string, { sum: number; count: number }>();
  for (const r of reviews) {
    const s = stats.get(r.listingId) ?? { sum: 0, count: 0 };
    s.sum += r.rating;
    s.count += 1;
    stats.set(r.listingId, s);
  }

  await prisma.listing.createMany({
    data: listings.map(({ photos, amenities, placeSlug, ...l }) => {
      const s = stats.get(l.id);
      return {
        ...l,
        organizationId,
        // Sub-lets earn Sigma the rent margin, not a commission (listings_sublease_commission_check).
        commissionBps: l.managementType === "SUBLEASE" ? 0 : org.defaultCommissionBps,
        licenseNumber: licenses.get(l.id)?.licenseNumber ?? null,
        licenseExpiresAt: licenses.get(l.id)?.licenseExpiresAt ?? null,
        placeId: placeIds.get(placeSlug)!,
        reviewCount: s?.count ?? 0,
        ratingAvg: s ? Math.round((s.sum / s.count) * 100) / 100 : null,
      };
    }),
  });
  await prisma.photo.createMany({
    data: listings.flatMap((l) => l.photos.map((url, position) => ({ listingId: l.id, url, position }))),
  });
  await prisma.listingAmenity.createMany({
    data: listings.flatMap((l) => l.amenities.map((amenityId) => ({ listingId: l.id, amenityId }))),
  });
  await prisma.review.createMany({ data: reviews.map((r) => ({ ...r, organizationId })) });

  // Seasons and events (Prix), then the bookings priced by the same engine as the site (lib/pricing/engine.ts).
  const rules = buildPriceRules(listings);
  await prisma.priceRule.createMany({
    data: rules.map(({ listingIds, ...r }) => ({ ...r, organizationId, adjustmentType: "PERCENT" as const, allListings: listingIds === null })),
  });
  await prisma.priceRuleListing.createMany({
    data: rules.flatMap((r) => (r.listingIds ?? []).map((listingId) => ({ ruleId: r.id, listingId, organizationId }))),
  });
  const engineRules: PricingRule[] = rules.map((r) => ({
    id: r.id,
    kind: r.kind,
    name: r.name,
    startDate: r.startDate.toISOString().slice(0, 10),
    endDate: r.endDate.toISOString().slice(0, 10),
    recurring: r.recurring,
    adjustment: { type: "PERCENT", bps: r.percentBps },
    minNights: r.minNights,
    priority: r.priority,
    listingIds: r.listingIds,
    createdAt: "2026-10-01T00:00:00.000Z",
  }));
  const byId = new Map(listings.map((l) => [l.id, l]));
  const amounts = (b: { listingId: string; checkIn: Date; checkOut: Date }) => {
    const p = priceStay(byId.get(b.listingId)!, engineRules, b.checkIn, b.checkOut);
    // nightlyCents: the average of the nights (Booking.nightlyCents); the total is the exact sum.
    return { nightlyCents: p.averageNightlyCents, cleaningFeeCents: p.cleaningFeeCents, serviceFeeCents: p.serviceFeeCents, totalCents: p.totalCents };
  };
  await prisma.booking.createMany({
    data: bookings.map((b) => ({ ...b, organizationId, source: "DIRECT" as const, ...amounts(b) })),
  });
  // Platform bookings carry the price as Sigma computes it; the platform's own figures (lot 7) come later.
  await prisma.booking.createMany({
    data: platform.map((b) => ({ ...b, organizationId, ...amounts(b) })),
  });
  // Owner blocks: dates only (bookings_owner_block_check).
  await prisma.booking.createMany({
    data: ownerBlocks.map((b) => ({ ...b, organizationId, source: "OWNER" as const, adults: 0 })),
  });

  // Field tasks: default check-lists (reset to the French defaults), then the tasks of the stays not over yet.
  for (const [type, items] of Object.entries(DEFAULT_CHECKLISTS)) {
    await prisma.checklistTemplate.upsert({
      where: { organizationId_type: { organizationId, type: type as keyof typeof DEFAULT_CHECKLISTS } },
      create: { organizationId, type: type as keyof typeof DEFAULT_CHECKLISTS, items },
      update: { items },
    });
  }
  const tasks = await backfillTasks(prisma, { organizationId });
  const week = await prisma.task.findMany({
    where: { organizationId, scheduledDate: { gte: today, lt: new Date(today.getTime() + 7 * 86_400_000) } },
    select: { id: true },
    orderBy: [{ scheduledDate: "asc" }, { startsAt: "asc" }, { id: "asc" }],
  });
  const agents = ["staff_agent_1", "staff_agent_2"];
  for (const [i, t] of week.entries()) {
    if (i % 3 === 2) continue;
    await prisma.task.update({ where: { id: t.id }, data: { assigneeId: agents[i % 3] } });
  }

  // Breakdown reports (Pannes): an urgent one on the first home, assigned to an agent; one waiting for a part.
  const [first, second] = listings.filter((l) => l.category === "HOME");
  const urgent = await prisma.ticket.create({
    data: { organizationId, listingId: first.id, title: "Climatisation du salon en panne", description: "Plus d'air froid depuis ce matin, voyageurs sur place.", category: "AIR_CONDITIONING", priority: "URGENT", reporterId: "staff_agent_1", assigneeId: "staff_agent_1" },
  });
  const waiting = await prisma.ticket.create({
    data: { organizationId, listingId: second.id, title: "Chasse d'eau qui fuit", category: "PLUMBING", priority: "NORMAL", status: "WAITING", waitingFor: "PART", reporterId: "staff_agent_2", assigneeId: "staff_agent_2" },
  });
  await prisma.ticketEvent.createMany({
    data: [
      { organizationId, ticketId: urgent.id, authorId: "staff_agent_1", kind: "CREATED", details: { priority: "URGENT", category: "AIR_CONDITIONING" } },
      { organizationId, ticketId: waiting.id, authorId: "staff_agent_2", kind: "CREATED", details: { priority: "NORMAL", category: "PLUMBING" } },
      { organizationId, ticketId: waiting.id, authorId: "staff_agent_2", kind: "STATUS", body: "Mécanisme commandé chez le quincaillier.", details: { from: "OPEN", to: "WAITING", waitingFor: "PART" } },
    ],
  });

  const guideLinks = await seedGuides(organizationId, listings, today);
  const travelers = await seedDeclarations(organizationId, guideLinks.find((g) => g.what === "séjour en cours")?.bookingId ?? null);
  const requests = await seedConcierge(organizationId, guideLinks.find((g) => g.what === "séjour en cours")?.bookingId ?? null, today);
  // After the declarations: the splits carry the demo stay's taxe de séjour.
  const finance = await seedFinances(organizationId, listings, waiting.id, today);

  console.log(
    `Seeded organization "${SIGMA_ORG.slug}", ${places.length} places, ${staff.length + owners.length + guests.length} users ` +
      `(${staff.length} staff, ${owners.length} owners), ${listings.length} listings ` +
      `(${listings.filter((l) => l.managementType === "SUBLEASE").length} sub-let), ` +
      `${reviews.length} reviews, ${bookings.length + platform.length + ownerBlocks.length} bookings ` +
      `(${bookings.length} direct, ${platform.length} from platforms, ${ownerBlocks.length} owner blocks), ${rules.length} price rules, ${tasks.created} field tasks, 2 breakdown reports, ${guideLinks.length} demo guide links, ${travelers} fictitious travellers and a demo taxe de séjour rate, ${DEMO_PARTNERS.length} demo partners, ${DEMO_SERVICES.length} services and ${requests} service requests, ${finance.splits} booking splits and ${finance.expenses} expenses.`,
  );
  for (const g of guideLinks) console.log(`  Guide (${g.what}): ${(process.env.BETTER_AUTH_URL ?? "http://localhost:3000").replace(/\/+$/, "")}/guide/${g.token}`);
}

/**
 * Finances (Lot 6), consistent with the bookings above: the split of every stay (computed by the app's own code,
 * lib/finance/post.ts), the platforms' figures of two of them (an Airbnb payout in MAD, a Booking.com total in euros
 * with an exchange rate typed by an associé), a monthly rent on each sub-let, and three expenses (a validated repair
 * rebilled to the owner, a validated purchase advanced by the owner, a draft); the breakdown waiting for a part gets a
 * cost « à refacturer », so that Finances proposes it as an expense. Fictitious amounts.
 */
async function seedFinances(organizationId: string, listings: ReturnType<typeof buildFixtures>["listings"], ticketId: string, today: Date): Promise<{ splits: number; expenses: number }> {
  const day = (n: number) => new Date(today.getTime() + n * 86_400_000);
  for (const l of listings.filter((x) => x.managementType === "SUBLEASE")) {
    await prisma.listing.update({ where: { id: l.id }, data: { subleaseRentCents: 900_000, subleaseRentFrom: new Date(Date.UTC(2026, 0, 1)) } });
  }
  const airbnb = await prisma.booking.findFirst({ where: { organizationId, source: "AIRBNB", totalCents: { not: null } }, orderBy: { checkIn: "asc" }, select: { id: true, totalCents: true } });
  if (airbnb) await prisma.booking.update({ where: { id: airbnb.id }, data: { platformAmountCents: Math.round((airbnb.totalCents! * 845) / 1000), platformCurrency: "MAD", platformAmountKind: "PAYOUT" } });
  const booking = await prisma.booking.findFirst({ where: { organizationId, source: "BOOKING", totalCents: { not: null } }, orderBy: { checkIn: "asc" }, select: { id: true, totalCents: true } });
  if (booking) await prisma.booking.update({ where: { id: booking.id }, data: { platformAmountCents: Math.round(booking.totalCents! / 10.85), platformCurrency: "EUR", platformAmountKind: "GUEST_TOTAL" } });
  const all = await prisma.booking.findMany({ where: { organizationId, source: { not: "OWNER" } }, select: { id: true }, orderBy: { checkIn: "asc" } });
  for (const b of all) await syncBookingFinance(prisma, b.id, { actorId: null });
  if (booking) {
    await prisma.bookingFinance.update({ where: { bookingId: booking.id }, data: { fxRateMicros: 10_850_000, inputsNote: "Taux du relevé Booking.com (démo)", inputsUpdatedAt: new Date(), inputsUpdatedById: "staff_amine" } });
    await syncBookingFinance(prisma, booking.id, { actorId: "staff_amine" });
  }
  await prisma.ticket.update({ where: { id: ticketId }, data: { costCents: 45_000, rechargeOwner: true } });

  const homes = listings.filter((l) => l.category === "HOME" && l.managementType === "MANAGED");
  const demo = [
    { id: "exp_demo_mitigeur", listing: homes[0], date: day(-12), category: "REPAIR" as const, description: "Remplacement du mitigeur de la salle de bain", supplier: "Quincaillerie de démonstration", amountCents: 34_990, paidBy: "SIGMA" as const, rebillToOwner: true, validate: true },
    { id: "exp_demo_bouilloire", listing: homes[1], date: day(-8), category: "PURCHASE" as const, description: "Bouilloire et grille-pain neufs", supplier: "Magasin de démonstration", amountCents: 52_000, paidBy: "OWNER" as const, rebillToOwner: false, validate: true },
    { id: "exp_demo_ampoules", listing: homes[0], date: day(-2), category: "SUPPLIES" as const, description: "Ampoules et piles des télécommandes", supplier: "", amountCents: 8_500, paidBy: "SIGMA" as const, rebillToOwner: true, validate: false },
  ];
  for (const e of demo) {
    if (!e.listing) continue;
    const { listing, validate, ...data } = e;
    await prisma.expense.create({ data: { ...data, organizationId, listingId: listing.id, createdById: "staff_amine" } });
    if (validate) {
      await prisma.$transaction(async (tx) => {
        await tx.expense.update({ where: { id: e.id }, data: { status: "VALIDATED", validatedAt: new Date(), validatedById: "staff_amine", ownerId: listing.ownerId } });
        await postExpense(tx, { ...data, organizationId, listingId: listing.id, ownerId: listing.ownerId }, "staff_amine");
      });
    }
  }
  return { splits: await prisma.bookingFinance.count({ where: { organizationId } }), expenses: demo.length };
}

/**
 * Welcome guides (Lot 4a): the conciergerie's contact, common recommendations, and for every home a guide in
 * French, Spanish and English with two access codes and the Wi-Fi, all encrypted with ACCESS_CODES_KEY (the same as
 * the app reading this database: the development key when unset outside production). Outside production, two demo
 * links with the known tokens of DEMO_GUIDE_TOKENS: a stay in progress (codes shown) and a stay to come.
 */
async function seedGuides(organizationId: string, listings: ReturnType<typeof buildFixtures>["listings"], today: Date) {
  await prisma.organization.update({ where: { id: organizationId }, data: DEMO_CONCIERGE });
  await prisma.guideRecommendation.createMany({
    data: DEMO_RECOMMENDATIONS.map((r, position) => ({ ...r, organizationId, listingId: null, position })),
  });
  const homes = listings.filter((l) => l.category === "HOME");
  await prisma.listingGuide.createMany({
    data: homes.map((l) => {
      const wifi = demoWifi(l.id);
      return {
        listingId: l.id,
        organizationId,
        ...demoGuideTexts(l.placeSlug),
        wifiName: wifi.wifiName,
        wifiPasswordEnc: encryptSecret(wifi.wifiPassword, { organizationId, listingId: l.id, purpose: "wifi" }),
      };
    }),
  });
  await prisma.guideAccessCode.createMany({
    data: homes.flatMap((l) =>
      demoAccessCodes(l.id).map((c, position) => ({
        organizationId,
        listingId: l.id,
        kind: c.kind,
        label: c.label,
        position,
        valueEnc: encryptSecret(c.value, { organizationId, listingId: l.id, purpose: "access-code" }),
      })),
    ),
  });
  // A recommendation of its own for the first Médina home.
  const medina = homes.find((l) => l.placeSlug === "medina");
  if (medina) {
    await prisma.guideRecommendation.create({
      data: { organizationId, listingId: medina.id, category: "CAFE", name: "Café du derb", description: { fr: "Au coin de la rue : thé à la menthe et msemen le matin.", es: "En la esquina: té a la menta y msemen por la mañana." } },
    });
  }
  if (process.env.NODE_ENV === "production") return [];

  const DAY = 86_400_000;
  // A guest stay in progress whatever the time of day (arrived yesterday or before, leaves in two days or later)…
  const current = await prisma.booking.findFirst({
    where: { organizationId, status: "CONFIRMED", source: { not: "OWNER" }, checkIn: { lte: new Date(today.getTime() - DAY) }, checkOut: { gte: new Date(today.getTime() + 2 * DAY) } },
    orderBy: { id: "asc" },
    select: { id: true },
  });
  // …and a direct stay to come.
  const upcoming = await prisma.booking.findFirst({
    where: { organizationId, status: "CONFIRMED", source: "DIRECT", checkIn: { gte: new Date(today.getTime() + 3 * DAY) } },
    orderBy: [{ checkIn: "asc" }, { id: "asc" }],
    select: { id: true },
  });
  const out: { what: string; bookingId: string; token: string }[] = [];
  for (const [what, b, token, guestLocale] of [
    ["séjour en cours", current, DEMO_GUIDE_TOKENS.current, null],
    ["séjour à venir", upcoming, DEMO_GUIDE_TOKENS.upcoming, "en"],
  ] as const) {
    if (!b) continue;
    await prisma.guideLink.create({
      data: { bookingId: b.id, organizationId, tokenHash: hashGuideToken(token), tokenEnc: encryptSecret(token, { organizationId, bookingId: b.id, purpose: "guide-token" }) },
    });
    if (guestLocale) await prisma.booking.update({ where: { id: b.id }, data: { guestLocale } });
    out.push({ what, bookingId: b.id, token });
  }
  return out;
}

/**
 * Lot 5, dev and test databases only: a DEMO taxe de séjour rate (a placeholder, labelled as such: not the commune's
 * rate) and, on the stay in progress, two obviously fictitious travellers (names « DEMO-… », documents « TEST00000x »),
 * encrypted with IDENTITY_DOCS_KEY like the app does, already declared, with the stay's tax computed by the app's
 * engine. Never any real identity.
 */
async function seedDeclarations(organizationId: string, bookingId: string | null): Promise<number> {
  if (process.env.NODE_ENV === "production") return 0;
  const rate = await prisma.touristTaxRate.create({ data: { organizationId, ...DEMO_TAX_RATE, effectiveFrom: new Date(`${DEMO_TAX_RATE.effectiveFrom}T00:00:00Z`) } });
  if (!bookingId) return 0;
  const b = await prisma.booking.findUniqueOrThrow({ where: { id: bookingId }, select: { id: true, listingId: true, checkIn: true, checkOut: true, adults: true, children: true, infants: true } });
  const iso = (d: Date) => d.toISOString().slice(0, 10);
  const people = DEMO_TRAVELERS.slice(0, Math.max(1, Math.min(b.adults, DEMO_TRAVELERS.length)));
  for (const [i, t] of people.entries()) {
    const id = `trvdemo${String(i + 1).padStart(4, "0")}`;
    await prisma.traveler.create({
      data: {
        id,
        organizationId,
        bookingId: b.id,
        isMinor: false,
        identityEnc: encryptIdentity({ ...t, arrivalDate: iso(b.checkIn), departureDate: iso(b.checkOut) }, { organizationId, bookingId: b.id, travelerId: id }),
        declaredAt: new Date(),
        declaredById: "staff_amine",
        createdById: "staff_amine",
      },
    });
  }
  const tax = computeStayTax({
    listingId: b.listingId,
    checkIn: iso(b.checkIn),
    checkOut: iso(b.checkOut),
    guests: taxGuests({ checkIn: iso(b.checkIn), adults: b.adults, children: b.children, infants: b.infants }, people.map((t) => ({ birthDate: t.birthDate, isMinor: false, residenceCountry: t.residenceCountry }))),
    orgVersions: [{ id: rate.id, effectiveFrom: DEMO_TAX_RATE.effectiveFrom, rateCents: rate.rateCents, minorsExemptUnder: rate.minorsExemptUnder, residentsExempt: rate.residentsExempt }],
  });
  await prisma.bookingTouristTax.create({
    data: {
      bookingId: b.id,
      organizationId,
      totalCents: tax.totalCents,
      nights: tax.nights,
      taxableGuestNights: tax.taxableGuestNights,
      exemptGuestNights: tax.exemptGuestNights,
      missingRateNights: tax.missingRateNights,
      basis: "TRAVELERS",
      lines: tax.lines as unknown as object[],
      computedAt: new Date(),
    },
  });
  return people.length;
}

/**
 * Conciergerie (Lot 4b): the demo partners and services (fictitious, prisma/fixtures.ts), and outside production two
 * requests on the stay in progress, priced by the app's own code (lib/concierge/pricing.ts): a hammam today, confirmed
 * and paid in cash, and an airport transfer on the departure morning, new.
 */
async function seedConcierge(organizationId: string, bookingId: string | null, today: Date): Promise<number> {
  await prisma.partner.createMany({ data: DEMO_PARTNERS.map((p) => ({ ...p, organizationId })) });
  await prisma.service.createMany({ data: DEMO_SERVICES.map((s, position) => ({ ...s, organizationId, position })) });
  if (process.env.NODE_ENV === "production" || !bookingId) return 0;
  const b = await prisma.booking.findUniqueOrThrow({ where: { id: bookingId }, select: { checkOut: true } });
  const at = (day: Date, minutes: number) => localInstant(day, minutes, "Africa/Casablanca");
  const svc = (id: string) => DEMO_SERVICES.find((s) => s.id === id)!;
  const rows = [
    { id: "sreqdemo0001", service: svc("svc_demo_hammam"), day: today, minutes: 18 * 60, persons: 2, quantity: 2, optionIds: [] as string[], status: "CONFIRMED" as const },
    { id: "sreqdemo0002", service: svc("svc_demo_transfert"), day: b.checkOut, minutes: 9 * 60, persons: 2, quantity: 1, optionIds: ["pancarte"], status: "NEW" as const },
  ];
  const now = new Date();
  for (const r of rows) {
    const options = r.service.options.filter((x) => r.optionIds.includes(x.id));
    const { totals } = lineTotals({ pricingModel: r.service.pricingModel, unitSaleCents: r.service.salePriceCents, unitPartnerCents: r.service.partnerPriceCents, quantity: r.quantity, persons: r.persons, options });
    const confirmed = r.status === "CONFIRMED";
    await prisma.serviceRequest.create({
      data: {
        id: r.id,
        organizationId,
        bookingId,
        serviceId: r.service.id,
        partnerId: r.service.partnerId,
        status: r.status,
        serviceDate: r.day,
        startMinutes: r.minutes,
        scheduledAt: at(r.day, r.minutes),
        quantity: r.quantity,
        persons: r.persons,
        titleSnapshot: r.service.title.fr,
        category: r.service.category,
        pricingModel: r.service.pricingModel,
        options,
        unitSaleCents: r.service.salePriceCents,
        unitPartnerCents: r.service.partnerPriceCents,
        saleTotalCents: totals?.saleTotalCents ?? null,
        partnerTotalCents: totals?.partnerTotalCents ?? null,
        marginCents: totals?.marginCents ?? null,
        guestNote: confirmed ? "" : "Vol de 13 h 05, demo",
        contactPhone: "+34 600 000 000",
        guestLocale: "fr",
        ...(confirmed && { sentAt: now, sentVia: "WHATSAPP" as const, confirmedAt: now, paymentMethod: "CASH" as const, paidAt: now, paidById: "staff_amine" }),
      },
    });
  }
  return rows.length;
}

/**
 * Passwords (and, for two staff members, double authentification) for a few demo accounts, so the back-office can
 * be tried and tested end to end. Dev and test databases only. The TOTP secret and backup codes are encrypted with
 * BETTER_AUTH_SECRET exactly as Better Auth stores them, so the app reading this database must use the same secret
 * (the test suites pass theirs to the seed).
 */
async function seedDemoLogins() {
  if (process.env.NODE_ENV === "production") {
    console.warn("NODE_ENV=production: demo accounts get no password and no double authentification.");
    return;
  }
  const password = await hashPassword(DEMO_PASSWORD);
  await prisma.account.createMany({
    data: DEMO_LOGINS.map(({ userId }) => ({ id: `acc_${userId}`, accountId: userId, providerId: "credential", userId, password })),
  });
  const key = process.env.BETTER_AUTH_SECRET;
  if (!key) {
    console.warn("BETTER_AUTH_SECRET is not set: demo staff get no double authentification (they will be asked to enroll).");
    return;
  }
  const withTotp = DEMO_LOGINS.filter((l) => l.totp).map((l) => l.userId);
  const backupCodes = await symmetricEncrypt({ key, data: JSON.stringify(DEMO_BACKUP_CODES) });
  for (const userId of withTotp) {
    const secret = await symmetricEncrypt({ key, data: DEMO_TOTP_SECRET });
    await prisma.twoFactor.create({ data: { id: `tf_${userId}`, userId, secret, backupCodes, verified: true } });
  }
  await prisma.user.updateMany({ where: { id: { in: withTotp } }, data: { twoFactorEnabled: true } });
}

